/** 规范化省份名称：数据库可能存 "山东"，表单/坐标表用 "山东省"。可供表单回显时使用 */
export function normalizeProvince(province: string): string {
  if (!province || province.length === 0) return province;
  const s = province.trim();
  if (s.endsWith('省') || s.endsWith('市') || s.endsWith('自治区')) return s;
  // 常见简称补全
  if (s === '山东') return '山东省';
  if (s === '山西') return '山西省';
  if (s === '河南') return '河南省';
  if (s === '河北') return '河北省';
  if (s === '江苏') return '江苏省';
  if (s === '浙江') return '浙江省';
  if (s === '安徽') return '安徽省';
  if (s === '福建') return '福建省';
  if (s === '江西') return '江西省';
  if (s === '湖北') return '湖北省';
  if (s === '湖南') return '湖南省';
  if (s === '广东') return '广东省';
  if (s === '海南') return '海南省';
  if (s === '四川') return '四川省';
  if (s === '贵州') return '贵州省';
  if (s === '云南') return '云南省';
  if (s === '陕西') return '陕西省';
  if (s === '甘肃') return '甘肃省';
  if (s === '青海') return '青海省';
  if (s === '辽宁') return '辽宁省';
  if (s === '吉林') return '吉林省';
  if (s === '黑龙江') return '黑龙江省';
  if (s === '内蒙古') return '内蒙古自治区';
  if (s === '广西') return '广西壮族自治区';
  if (s === '西藏') return '西藏自治区';
  if (s === '宁夏') return '宁夏回族自治区';
  if (s === '新疆') return '新疆维吾尔自治区';
  return s + '省';
}

/**
 * 根据省市区获取坐标
 * @param province 省份（支持 "山东" 或 "山东省"）
 * @param city 城市
 * @returns [经度, 纬度]
 */
export function getCityCoordinates(
  province: string,
  city: string
): [number, number] {
  const prov = normalizeProvince(province || '');
  const cityName = (city || '').trim();

  // 优先使用精确的省+市匹配
  const cityCoord = cityCoordinates[prov]?.[cityName];
  if (cityCoord) {
    return cityCoord;
  }

  // 如果找不到，使用省份中心坐标
  const provinceCoord = provinceCenters[prov];
  if (provinceCoord) {
    return provinceCoord;
  }

  // 默认返回中国中心坐标（北京附近）
  return [104.0, 35.0];
}
